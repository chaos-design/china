/** 依据类型与品级兜底的通用说明：词典未命中且节点自身无 note 时使用。 */
function genericDuty(node: OfficeTreeNode): OfficeDuty {
  switch (node.kind) {
    case "root":
      return {
        scope: "统辖全部官署的最高权力",
        function: "国家权力的本源，所有衙署均由此分职而治",
      };
    case "honorary":
      return {
        scope: "荣誉性封号，无独立衙署",
        function: "作为品级与位望的标志，多加于重臣或宗室，备顾问与辅政象征",
      };
    case "branch":
      return {
        scope: `一类中央或地方机构的统称${node.rank ? `，辖内官品级 ${node.rank}` : ""}`,
        function: "统率所属衙署分职办事，向皇帝或上级机构负责",
      };
    case "office":
      return {
        scope: `隶属上级机构的属官${node.rank ? `，品级 ${node.rank}` : ""}`,
        function: "分管具体事务、承上启下，是官制中直接办事的一层",
      };
  }
}

/** 取节点的职权范围与职能：优先词典，其次节点自身 note，最后按类型兜底。 */
export function getOfficeDuty(node: OfficeTreeNode): OfficeDuty {
  const hit = DUTIES[node.title] ?? DUTIES[node.title.replace(/\s*\/.*$/, "")];
  if (hit) {
    return hit;
  }
  if (node.note) {
    return { scope: "承本衙署分职，职权见下方说明", function: node.note };
  }
  return genericDuty(node);
}
