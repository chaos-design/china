/** 取本朝读图口径；未单列的朝代由现有数据兜底，保证新增数据不会让气泡空白。 */
export function getReadingGuide(atlas: DynastyAtlas): ReadingGuide {
  const guide = GUIDES[atlas.id];
  if (guide) {
    return guide;
  }
  return {
    institution: {
      title: atlas.system,
      body: `${atlas.intro}本朝层级以${atlas.root.title}为权力本源，${atlas.branches
        .map((entry) => entry.title)
        .join("、")}分职；品秩口径见「${atlas.rankSystemLabel}」。${atlas.hierarchyNote}`,
    },
    citations: [{ source: atlas.source, note: "本页官名、品秩与沿革均据此文献体系整理。" }],
    example: {
      path: `${atlas.root.title} → ${atlas.branches[0]?.title ?? "官署分区"} → ${
        atlas.branches[0]?.nodes[0]?.title ?? "属官"
      }`,
      body: "点选节点或标签即可展开详情，右侧面板同步显示从属路径、职掌与品级实档。",
    },
  };
}
