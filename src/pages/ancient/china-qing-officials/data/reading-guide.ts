/**
 * 立体树的「读图」文案层。
 *
 * 舞台气泡不重复节点详情，而是回答三件事：面片怎么读、本朝制度怎么定位、
 * 这句话出自哪部书。每朝一份制度口径与文献依据，由注册表统一取用。
 */
export interface ReadingCitation {
  /** 文献出处，正史或典章书名。 */
  source: string;
  /** 可核对的原句；没有确切文本时留空，只写出处与释义。 */
  quote?: string;
  /** 这句文献在这张图上的对应点。 */
  note: string;
}

export interface ReadingGuide {
  /** 本朝制度的密集说明，气泡的第二屏。 */
  institution: { title: string; body: string };
  /** 文献依据，至少两条，给出可回查的出处。 */
  citations: readonly ReadingCitation[];
  /** 一条从权力本源走到基层的具体从属链。 */
  example: { path: string; body: string };
}

