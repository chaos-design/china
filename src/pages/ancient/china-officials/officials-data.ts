export function getOfficialsDynasty(id: string): OfficialsDynasty | undefined {
  return OFFICIALS_DYNASTIES.find((dynasty) => dynasty.id === id);
}

export function countPosts(dynasty: OfficialsDynasty): number {
  return dynasty.grades.reduce((total, item) => total + item.posts.length, 0);
}

export function branchCounts(item: OfficialGrade): { civil: number; military: number } {
  return {
    civil: item.posts.filter((postItem) => postItem.branch === "civil").length,
    military: item.posts.filter((postItem) => postItem.branch === "military").length,
  };
}

/** 找出某朝、某级、某官职；详情抽屉只按这三个键定位，不引入独立页面。 */
export function findPost(
  dynasty: OfficialsDynasty,
  gradeId: string,
  title: string,
): { grade: OfficialGrade; post: OfficialPost } | null {
  const targetGrade = dynasty.grades.find((item) => item.id === gradeId);
  const post = targetGrade?.posts.find((item) => item.title === title);
  return targetGrade && post ? { grade: targetGrade, post } : null;
}
