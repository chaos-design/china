/**
 * 官职体系（品秩全景）数据。
 *
 * 与「品级纵横」不同，这里立体场景**只以品级为节点**：具体官职是每一级的名录，
 * 按文官 / 武官分组，点名录中的官职才在同一层级展开详情抽屉。
 *
 * 职位一律用确切官名（如「廷尉」「折冲都尉」「六科给事中」），不写「九卿」「诸卫」
 * 这类笼统类别；人物示例取该朝实任、加衔、差遣或追赠此职者，仅作参照，不作严格同品对应。
 * 品秩以正史职官志的通行记载为准，官、职、差遣分离之处在 rankNote / caption 里说明。
 */

export type OfficialsDynastyId =
  | "qin"
  | "han"
  | "weijin"
  | "suitang"
  | "song"
  | "yuan"
  | "ming"
  | "qing";

export type OfficeBranch = "civil" | "military";

export interface OfficialFigure {
  /** 人物与该职的关系一句话。 */
  note: string;
  name: string;
}

export interface OfficialPost {
  branch: OfficeBranch;
  /** 简明的职掌介绍，一句话。 */
  intro: string;
  /** 与本级常例品秩不同时的说明，如差遣、加衔、本官品卑而权重。 */
  rankNote?: string;
  title: string;
  figures?: readonly OfficialFigure[];
}

export interface OfficialGrade {
  /** 该级的制度口径，一两句。 */
  caption: string;
  id: string;
  label: string;
  /** 0 超品、1…9 品、10 未入流；用于同一根品序轴对齐。 */
  order: number;
  /** 秦汉无品时的示意标注。 */
  approx?: string;
  posts: readonly OfficialPost[];
}

export interface OfficialsDynasty {
  grades: readonly OfficialGrade[];
  id: OfficialsDynastyId;
  name: string;
  period: string;
  source: string;
  summary: string;
  system: string;
}

function f(name: string, note: string): OfficialFigure {
  return { name, note };
}

function post(
  title: string,
  branch: OfficeBranch,
  intro: string,
  extra: { figures?: readonly OfficialFigure[]; rankNote?: string } = {},
): OfficialPost {
  return { branch, intro, title, ...extra };
}

function grade(
  id: string,
  label: string,
  order: number,
  caption: string,
  posts: readonly OfficialPost[],
  approx?: string,
): OfficialGrade {
  return { approx, caption, id, label, order, posts };
}

